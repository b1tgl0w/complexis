function getClockDirection(center: Coord, d: Coord): number {
  // Assumes center and d are adj.
  if (d.row === center.row - 1) {
    if (d.col === center.col - 1)
      return 11;
    if (d.col === center.col)
      return 12;
    if (d.col === center.col + 1)
      return 1;
  }
  if (d.row === center.row) {
    if (d.col === center.col - 1)
      return 9;
    if (d.col === center.col)
      return 0;
    if (d.col === center.col + 1)
      return 3;
  }
  if (d.row === center.row + 1) {
    if (d.col === center.col - 1)
      return 7;
    if (d.col === center.col)
      return 6;
    if (d.col === center.col + 1)
      return 5;
  }

  return undefined;
}

