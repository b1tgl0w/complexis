Coord getPotentialCoords(const Coord & coords, int clockDirection) {
  int y = coords.row;
  int x = coords.col;

  if (clockDirection == 12)
    y -= 1;
  if (clockDirection == 1) {
    y -= 1;
    x += 1;
  }
  if (clockDirection == 3)
    x += 1;
  if (clockDirection == 5) {
    y += 1;
    x += 1;
  }
  if (clockDirection == 6)
    y += 1;
  if (clockDirection == 7) {
    y += 1;
    x -= 1;
  }
  if (clockDirection == 9)
    x -= 1;
  if (clockDirection == 11) {
    y -= 1;
    x -= 1;
  }

  if (y < 0 || y >= wholeLength)
    y = -1;

  if (x < 0 || x >= whole0Length)
    x = -1;

  return { .row = y, .col = x };
}

bool isOpen(const Coord & coords, Uint32 potentialWhole[][whole0Length]) {
  if (coords.col < 0 || coords.row < 0)
    return false;
  if (coords.col + wholecoord.col < 0)
    return false;
  if (coords.row + wholecoord.row < 0)
    return false;
  if (coords.col + wholecoord.col >= board0Length)
    return false;
  if (coords.row + wholecoord.row >= boardLength)
    return false;

  if (board[coords.row + wholecoord.row][coords.col + wholecoord.col])
    return false;

  return potentialWhole[coords.row][coords.col] == bgcolor;
}

